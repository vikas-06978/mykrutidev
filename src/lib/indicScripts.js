/**
 * Hindi (Devanagari) -> another Indian script, letter for letter.
 *
 * Not a translation. Each Hindi letter is written with the same letter of the
 * other script, so भारत becomes ভারত (Bengali) or ભારત (Gujarati) and still
 * says "bhaarat". The scripts were laid out in Unicode in parallel (क sits at
 * the same place in every block), and TABLES below was generated from that
 * layout and then CHECKED NAME BY NAME against the Unicode character
 * database (Python unicodedata 14.0): a letter is only mapped when the two
 * characters carry the same official name, or when the only difference is how
 * the target script names its long and short e and o (Hindi ए is long, so it
 * is Telugu ఏ "EE", not ఎ "E"). Nothing here was typed by hand except:
 *
 *  - व in Bengali and Odia, which have no separate va letter and write it
 *    with ba (ব, ବ). That is how those languages spell it.
 *  - The nukta (the dot in ज़, फ़) is left out for Telugu and Malayalam: Telugu
 *    only gained one in 2021 and few fonts draw it, and Malayalam has none.
 *    ज़ becomes జ, which is how Telugu writers spell it.
 *
 * Anything else the target script has no letter for (ॉ in Bengali, for
 * example) is left exactly as it was and reported, never guessed.
 *
 * Shared marks stay as they are: the danda । ॥ is the one Unicode character
 * every one of these scripts uses, and spaces, punctuation, Latin text and
 * ASCII digits need no change.
 */

