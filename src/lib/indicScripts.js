// The nukta is dropped, not left behind as a Devanagari mark (see above).
TABLES.telugu['\u093C'] = '';
TABLES.malayalam['\u093C'] = '';

/** The scripts offered, keyed the way TABLES is. */
export const SCRIPTS = Object.keys(TABLES);

// Precomposed nukta letters (क़ U+0958 ...) are decomposed first, so they are
// looked up as क + ़ like any other. NFD does exactly that for this block.
const RE_DEVANAGARI = /[ऀ-ॿ]/;

/**
 * @param {string} text Hindi (Devanagari) text
 * @param {string} script one of SCRIPTS
 * @returns {{ text: string, missed: string[] }} the converted text, and the
 *   Devanagari characters the target had no letter for (left unchanged)
 */
export function toScript(text, script) {
  const table = TABLES[script];
  if (!table) throw new Error(`Unknown script: ${script}`);
  const missed = new Set();
  let out = '';
  for (const ch of text.normalize('NFD')) {
    const t = table[ch];
    if (t !== undefined) out += t;
    else {
      // The danda and double danda are shared by all these scripts.
      if (RE_DEVANAGARI.test(ch) && ch !== '।' && ch !== '॥') missed.add(ch);
      out += ch;
    }
  }
  return { text: out.normalize('NFC'), missed: [...missed] };
}
