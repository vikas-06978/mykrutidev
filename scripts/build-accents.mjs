// Writes src/styles/accents.css: the five accent colours for every theme, each
// with its lightness tuned until it passes AA on that theme's backgrounds.
// Run after changing a theme's colours: `node scripts/build-accents.mjs`.
// src/lib/themes.test.js fails if the file is out of date.
import { readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';

import { ACCENTS, THEMES, accentFor, readThemes } from '../src/lib/themeColors.js';

const styles = new URL('../src/styles/', import.meta.url);

export function buildAccentsCss() {
  const themes = readThemes(
    readFileSync(new URL('global.css', styles), 'utf8'),
    readFileSync(new URL('themes.css', styles), 'utf8'),
  );
  const names = Object.keys(ACCENTS);
  /** --accent-* for one theme, as declarations. */
  const vars = (theme, indent) =>
    names
      .map((a) => {
        const { base, deep, on } = accentFor(theme, themes[theme], a);
        return [
          `${indent}--accent-${a}: ${base};`,
          `${indent}--accent-${a}-deep: ${deep};`,
          `${indent}--accent-${a}-on: ${on};`,
        ].join('\n');
      })
      .join('\n');

  const visual = THEMES.filter((t) => t !== 'contrast');
  const lines = [
    '/* GENERATED by scripts/build-accents.mjs from global.css + themes.css.',
    '   Do not edit by hand - change the theme colours, then re-run the script.',
    '',
    '   --accent-<name>[-deep|-on] per theme; the chosen accent (data-accent on',
    '   <html>) is mapped onto --color-brick at the end. High contrast ignores',
    '   it and keeps its own yellow (see themes.css). */',
    '',
    ':root {',
    vars('light', '  '),
    '}',
    '',
    '@media screen {',
    ...visual.slice(1).flatMap((t) => [`  :root[data-theme='${t}'] {`, vars(t, '    '), '  }']),
    '}',
    '',
    '/* The chosen accent becomes the site accent. */',
    ...names.flatMap((a) => [
      `:root[data-accent='${a}'] {`,
      `  --color-brick: var(--accent-${a});`,
      `  --color-brick-deep: var(--accent-${a}-deep);`,
      `  --color-on-brick: var(--accent-${a}-on);`,
      `  --color-focus: var(--accent-${a});`,
      '}',
    ]),
    '',
    '/* Theme cards in the picker preview their own theme, in the chosen accent. */',
    ...THEMES.flatMap((t) => {
      const tk = themes[t];
      const accentVars =
        t === 'contrast'
          ? names.map((a) => `  --pa-${a}: ${tk.brick};`)
          : names.map((a) => `  --pa-${a}: ${accentFor(t, tk, a).base};`);
      return [
        `[data-theme-card='${t}'] {`,
        `  --pp: ${tk.paper};`,
        `  --ps: ${tk.surface};`,
        `  --pt: ${tk.ink};`,
        `  --pm: ${tk.mute};`,
        `  --pl: ${tk.hairline};`,
        ...accentVars,
        '}',
      ];
    }),
    ...names.map((a) => `:root[data-accent='${a}'] [data-theme-card] { --pa: var(--pa-${a}); }`),
    '',
  ];
  return lines.join('\n');
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  const css = buildAccentsCss();
  writeFileSync(new URL('accents.css', styles), css);
  console.log(`accents.css: ${css.split('\n').length} lines`);
}
