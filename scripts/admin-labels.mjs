// `npm run admin-labels`: writes server/adminLabels.js, the English labels the
// private feedback page shows, from src/i18n/en.json.
//
// A generated module rather than a JSON import. Cloudflare's Pages Functions
// bundler (wrangler 3, with esbuild 0.17) cannot parse import attributes
// (`with { type: 'json' }`), while Node refuses a JSON import without them. A
// plain .js module works in both. server/feedback.test.js fails if the file is
// out of date with en.json.
import { readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';

const root = fileURLToPath(new URL('..', import.meta.url));
const en = JSON.parse(readFileSync(`${root}src/i18n/en.json`, 'utf8'));
const { ratings, used, wants } = en.feedback;

const out = `// Generated by scripts/admin-labels.mjs from src/i18n/en.json. Do not edit:
// change en.json, then run \`npm run admin-labels\`.
export const LABELS = ${JSON.stringify({ ratings, used, wants }, null, 2)};
`;
writeFileSync(`${root}server/adminLabels.js`, out);
console.log('server/adminLabels.js written');
