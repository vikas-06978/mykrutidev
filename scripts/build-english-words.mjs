#!/usr/bin/env node
/**
 * Builds public/data/english-words.json: the ~20k most common English words,
 * each with its CMU pronunciation (ARPAbet, stress digits stripped).
 *
 *   node scripts/build-english-words.mjs
 *
 * Sources, downloaded into vendor/english/ (gitignored) on first run:
 *
 *   cmudict.dict  CMU Pronouncing Dictionary      BSD-2-Clause, (C) Carnegie
 *                 github.com/cmusphinx/cmudict     Mellon University
 *   en_50k.txt    English word frequencies from    CC BY-SA 4.0, Hermit Dave
 *                 OpenSubtitles 2018               github.com/hermitdave/FrequencyWords
 *
 * The frequency list only decides WHICH words are in; every pronunciation is
 * CMU's. A word makes the cut if it is in both lists, is at least two letters
 * (so Hinglish `a` for आ is never read as the English article), and is among
 * the first 20,000 such words by frequency.
 *
 * Deciding whether a word is English or Hinglish is NOT done here - that is
 * src/lib/englishWords.js, at runtime, so the Hinglish list can change
 * without regenerating this file.
 */

import { existsSync, mkdirSync, readFileSync, writeFileSync } from 'node:fs';

const ROOT = new URL('../', import.meta.url);
const VENDOR = new URL('vendor/english/', ROOT);
const OUT = new URL('public/data/english-words.json', ROOT);
const LIMIT = 20_000;

const SOURCES = {
  'cmudict.dict': 'https://raw.githubusercontent.com/cmusphinx/cmudict/master/cmudict.dict',
  'cmudict.LICENSE': 'https://raw.githubusercontent.com/cmusphinx/cmudict/master/LICENSE',
  'en_50k.txt':
    'https://raw.githubusercontent.com/hermitdave/FrequencyWords/master/content/2018/en/en_50k.txt',
};

mkdirSync(VENDOR, { recursive: true });
for (const [name, url] of Object.entries(SOURCES)) {
  const file = new URL(name, VENDOR);
  if (existsSync(file)) continue;
  console.log(`downloading ${name}`);
  const res = await fetch(url);
  if (!res.ok) throw new Error(`${url}: HTTP ${res.status}`);
  writeFileSync(file, await res.text());
}

// First pronunciation only: `word(2)` variants are alternatives, and the
// first is CMU's primary.
const cmu = new Map();
for (const line of readFileSync(new URL('cmudict.dict', VENDOR), 'utf8').split('\n')) {
  const m = /^([a-z]+)\s+([^#]+)/.exec(line);
  if (m && !cmu.has(m[1])) cmu.set(m[1], m[2].trim().replace(/\d/g, ''));
}

const words = {};
let n = 0;
for (const line of readFileSync(new URL('en_50k.txt', VENDOR), 'utf8').split('\n')) {
  const w = line.split(' ')[0];
  if (!/^[a-z]{2,}$/.test(w) || !cmu.has(w) || w in words) continue;
  words[w] = cmu.get(w);
  if (++n === LIMIT) break;
}

const out = {
  _about:
    'Common English words with CMU Pronouncing Dictionary pronunciations. ' +
    'Pronunciations (C) 1993-2015 Carnegie Mellon University, BSD-2-Clause. ' +
    'Word selection by frequency from FrequencyWords (Hermit Dave), CC BY-SA 4.0. ' +
    'Generated by scripts/build-english-words.mjs - do not edit by hand.',
  words,
};
mkdirSync(new URL('public/data/', ROOT), { recursive: true });
writeFileSync(OUT, JSON.stringify(out));
console.log(`wrote ${n} words to public/data/english-words.json`);
